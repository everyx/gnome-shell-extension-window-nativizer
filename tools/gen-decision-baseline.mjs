#!/usr/bin/env node
/**
 * gen-decision-baseline.mjs - Runs the decision corpus (tools/decision-baseline-cases.mjs) through
 * `evaluateWindowActions` and records the output, so a reshape of the decision layer can be
 * checked against what it used to do instead of against a claim.
 *
 * The record is the *output only*, one line per case in corpus order: the five action booleans, a
 * semantic digest of the resolved style, and the reason. A key that stops matching shows up in the
 * reason ("rule-applied(...)" disappears), which is how the ring-predicate unification is meant to
 * be caught - so no key has to be stored, and the file stays a size worth reading.
 *
 * Usage: node tools/gen-decision-baseline.mjs [--check] [--verbose]
 *   (no flag) / --update : rewrite tools/decision-baseline.json
 *   --check              : re-derive and fail on any difference (check-style)
 *   --verbose            : on --check failure, print every differing case, not just the first 20
 */

import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

import {evaluateWindowActions, declaredSides} from '../src/lib/detector.js';
import {extractWindowProperties} from '../src/lib/pick.js';
import {kindFromProperties} from '../src/lib/rules.js';
import {buildCases} from './decision-baseline-cases.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'tools', 'decision-baseline.json');
const CHECK = process.argv.includes('--check');
const VERBOSE = process.argv.includes('--verbose');

/** Semantic digest of a resolved style: what the shadow actor and the clip actually consume. */
function styleDigest(style) {
    const layers = (style.shadows ?? []).map(l => `${l.blur}/${l.spread}/${l.alpha}`).join(';');
    return [
        `r${style.radius}`,
        `n${(style.shadows ?? []).length}`,
        style.animate ? 'A' : '-',
        style.outline ? 'O' : '-',
        style.border ? 'B' : '-',
        layers,
    ].join(',');
}

/**
 * The rule array a case runs against. The kind is built the way `Manager` builds it
 * for a pick - through `extractWindowProperties`, not by hand - so the corpus pins the
 * picker's kind against the runtime's reading. `foreign` stores the matching kind
 * under a different identity, which is the one shape that can never match.
 * @param {object} params
 * @param {string|null} ruleState
 * @param {boolean} foreign
 * @returns {Array<{kind: object, state: string, title: string}>}
 */
function rulesFor(params, ruleState, foreign) {
    if (!ruleState && !foreign)
        return [];

    const properties = extractWindowProperties(params, params.wmClass);
    const kind = kindFromProperties(properties);
    if (!kind)
        return [];

    return [{kind: foreign ? {...kind, identity: 'other'} : kind, state: ruleState ?? 'corners', title: ''}];
}

/** @param {object} c @returns {string} One recorded line for the case */
function evaluate(c) {
    const params = {...c.params, rules: rulesFor(c.params, c.ruleState, c.ruleForeign)};
    try {
        const actions = evaluateWindowActions(params);
        const bits = [actions.drawShadow, actions.drawClip, actions.clearRing, actions.drawRing, actions.drawResize]
            .map(b => (b ? 1 : 0)).join('');
        return `${bits}|${styleDigest(actions.style)}|${actions.reason}`;
    } catch (e) {
        // A throw is a behaviour too: pin it rather than letting the tool die on the case.
        return `THROW|${e.message}`;
    }
}

/** A one-line description of a case, for a failure report. */
function describe(c) {
    const p = c.params;
    const {declaringSides} = declaredSides({
        insets: p.insets,
        bufferWidth: p.bufferWidth, bufferHeight: p.bufferHeight,
        frameWidth: p.frameWidth, frameHeight: p.frameHeight,
    });
    const parts = [
        `type=${p.windowType}`,
        `size=${p.bufferWidth}x${p.bufferHeight}`,
        `frame=${p.frameWidth}x${p.frameHeight}`,
        `insets=${p.insets ? 'readable' : 'null'}`,
        `sides=${declaringSides.sideW.toFixed(1)}x${declaringSides.sideH.toFixed(1)}`,
        `readRing=${p.hasRing}`,
        `ssd=${p.hasSsd}`,
        `x11=${p.isX11}`,
        `native=${p.nativeLikeCorners}`,
        `gtk4=${p.hasGtk4Client}`,
        `resizable=${p.allowsResize}`,
        `max=${p.isMaximized}`,
        `full=${p.isFullscreen}`,
        `tiled=${p.tiled}`,
        `match=${p.hasTileMatch}`,
        `focused=${p.focused}`,
        `contrast=${p.highContrast}`,
        `crisp=${p.preferCrispText}`,
        `scale=${p.monitorScale}`,
        `rule=${c.ruleForeign ? 'foreign' : c.ruleState ?? 'none'}`,
    ];
    return parts.join(' ');
}

function main() {
    const cases = buildCases();
    const outputs = cases.map(evaluate);

    if (!CHECK) {
        const payload = {
            _comment: 'Generated by tools/gen-decision-baseline.mjs. One line per case in tools/decision-baseline-cases.mjs order; see that file for the corpus. Do not edit by hand.',
            cases: cases.length,
            outputs,
        };
        writeFileSync(OUT, `${JSON.stringify(payload, null, 4)}\n`, 'utf8');
        console.log(`[gen-decision-baseline] wrote ${cases.length} cases to ${path.relative(ROOT, OUT)}`);
        return;
    }

    if (!existsSync(OUT)) {
        console.error(`[gen-decision-baseline] --check failed: ${path.relative(ROOT, OUT)} does not exist`);
        process.exit(1);
    }

    let record;
    try {
        record = JSON.parse(readFileSync(OUT, 'utf8'));
    } catch (e) {
        console.error(`[gen-decision-baseline] --check failed: cannot read the record: ${e.message}`);
        process.exit(1);
    }

    if (record.cases !== cases.length) {
        console.error(`[gen-decision-baseline] --check failed: the corpus has ${cases.length} cases, ` +
            `the record has ${record.cases}. Regenerate with tools/gen-decision-baseline.mjs.`);
        process.exit(1);
    }

    const diffs = [];
    for (let i = 0; i < cases.length; i++) {
        if (record.outputs[i] !== outputs[i])
            diffs.push(i);
    }

    if (diffs.length === 0) {
        console.log(`[gen-decision-baseline] --check passed: ${cases.length} decisions match the record`);
        return;
    }

    const shown = VERBOSE ? diffs : diffs.slice(0, 20);
    for (const i of shown) {
        console.error(`\n  #${i} ${cases[i].label}  (${describe(cases[i])})`);
        console.error(`    recorded: ${record.outputs[i]}`);
        console.error(`    current : ${outputs[i]}`);
    }
    if (shown.length < diffs.length)
        console.error(`\n  ... and ${diffs.length - shown.length} more (rerun with --verbose)`);

    console.error(`\n[gen-decision-baseline] --check failed: ${diffs.length}/${cases.length} decisions changed. ` +
        'If the change is intended, regenerate and review the diff.');
    process.exit(1);
}

main();
