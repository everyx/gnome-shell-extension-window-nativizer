#!/usr/bin/env node
/**
 * gen-inspector.mjs - Reads vendor/gnome-shell and generates src/lib/inspectorStyle.generated.js
 * (the metrics of the picker's window highlight).
 *
 * Design: narrow parser + assertions. Each value is taken from the one place upstream states it, and
 * a value that no longer matches its shape aborts the run rather than being emitted: the border is a
 * local constant in the Looking Glass picker, the fill is a colour expression in the screenshot
 * window selector's stylesheet.
 *
 * Usage: node tools/gen-inspector.mjs [--check]
 *   --check: Verifies generated results match existing files (used by CI / check-style), exits with 1 if mismatch.
 */

import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = path.join(ROOT, 'vendor', 'gnome-shell');
const OUT = path.join(ROOT, 'src', 'lib', 'inspectorStyle.generated.js');

const CHECK = process.argv.includes('--check');

function read(name) {
    const p = path.join(VENDOR, name);
    if (!existsSync(p))
        throw new Error(`[gen-inspector] Missing vendor file: ${name}`);
    return readFileSync(p, 'utf8');
}

/**
 * The border Looking Glass paints inside the actor's allocation:
 * `const width = 2;` in RedBorderEffect.vfunc_paint_node(). The name is generic, so the assertion
 * is that the file holds exactly one such declaration - a second one means the anchor moved.
 */
function parseLookingGlassBorder(js) {
    const matches = js.match(/^\s*const width = (\d+);$/gm) ?? [];
    if (matches.length !== 1)
        throw new Error(`[gen-inspector] Assertion failed: expected exactly one "const width = N;" in lookingGlass.js, found ${matches.length}`);
    return parseInt(matches[0].match(/(\d+)/)[1], 10);
}

/**
 * The fill the screenshot window selector gives the window it highlights:
 * `st-transparentize(-st-accent-color, 0.8)`.
 */
function parseScreenshotFill(scss) {
    const m = scss.match(/background-color:\s*st-transparentize\(-st-accent-color,\s*([\d.]+)\);/);
    if (!m)
        throw new Error('[gen-inspector] Assertion failed: no st-transparentize(-st-accent-color, ...) fill in _screenshot.scss');
    return parseFloat(m[1]);
}

function main() {
    const borderWidth = parseLookingGlassBorder(read('lookingGlass.js'));
    const bgTransparentize = parseScreenshotFill(read('_screenshot.scss'));

    if (borderWidth < 1 || borderWidth > 8)
        throw new Error(`[gen-inspector] Assertion failed: unexpected picker border width ${borderWidth}`);
    if (!(bgTransparentize > 0 && bgTransparentize < 1))
        throw new Error(`[gen-inspector] Assertion failed: unexpected highlight fill ${bgTransparentize}`);

    const commit = read('COMMIT').trim();
    const code = `/**
 * Picker highlight metrics (**Generated file, do not edit directly**).
 *
 * Source: upstream gnome-shell (vendor/gnome-shell/COMMIT = ${commit})
 *   HIGHLIGHT_BORDER_WIDTH - js/ui/lookingGlass.js, the border the Looking Glass picker draws around
 *     the actor it is inspecting. Sized from that picker rather than from the screenshot window
 *     selector's 6px, which is a thumbnail grid rather than a hover-and-pick tool.
 *   HIGHLIGHT_BG_TRANSPARENTIZE - data/theme/gnome-shell-sass/widgets/_screenshot.scss, the fill the
 *     screenshot window selector gives the window it highlights.
 * Generated by: node tools/gen-inspector.mjs
 */

export const HIGHLIGHT_BORDER_WIDTH = ${borderWidth};
export const HIGHLIGHT_BG_TRANSPARENTIZE = ${bgTransparentize};
`;

    if (CHECK) {
        if (!existsSync(OUT)) {
            console.error(`[gen-inspector] --check failed: ${OUT} does not exist`);
            process.exit(1);
        }
        if (readFileSync(OUT, 'utf8') !== code) {
            console.error(`[gen-inspector] --check failed: ${OUT} does not match vendor/gnome-shell`);
            process.exit(1);
        }
        console.log(`[gen-inspector] --check passed: picker highlight matches vendor source (commit ${commit.slice(0, 8)})`);
        return;
    }

    writeFileSync(OUT, code, 'utf8');
    console.log(`[gen-inspector] Successfully parsed and generated: ${path.relative(ROOT, OUT)}`);
}

main();
